/**
 * Branch identity snapshot.
 *
 * A branch records which agent version a run belongs to and, for forked runs, where it
 * branched from. Snapshots are validated once so every later comparison is a plain
 * value comparison rather than a re-validation.
 *
 * Exports: `snapshotBranch`.
 */
import type { AgentBranch } from './engine.js';
import { breakWhile } from '../utils/rules.js';

/**
 * Validate and freeze a branch identity.
 *
 * Required ids identify the branch itself; optional ids describe the fork origin. Ids are
 * bounded in length so they remain usable as keys in App storage.
 *
 * @param source - Branch identity supplied by the host or generated by the engine.
 * @returns A frozen identity with the same field set.
 * @throws Error When a required id is missing or any id is blank or too long.
 */
export function snapshotBranch(source: AgentBranch): AgentBranch {
  breakWhile(!source, 'Invalid branch identity');
  const { agentId, branchId, agentVersionId, parentBranchId, parentAgentVersionId, forkPointId } =
    source;
  const valid = (id: unknown) => typeof id === 'string' && !!id.trim() && id.length <= 200;
  breakWhile(
    ![agentId, branchId, agentVersionId].every(valid) ||
      [parentBranchId, parentAgentVersionId, forkPointId].some(
        (id) => id !== undefined && !valid(id),
      ),
    'Invalid branch identity',
  );
  return Object.freeze({
    agentId,
    branchId,
    agentVersionId,
    parentBranchId,
    parentAgentVersionId,
    forkPointId,
  });
}
