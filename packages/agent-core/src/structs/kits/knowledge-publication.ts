/**
 * Knowledge publication contract: staged document revisions with explicit provenance.
 *
 * Place in the package: an optional App-side workflow for proposing, publishing or rejecting a
 * knowledge document. Candidates are validated against the same catalog compiler as published
 * documents and expire unless published; the store performs one atomic revision swap.
 *
 * Exports: `knowledgePublicationOperations`, `KnowledgeSourceReference`, `KnowledgeCandidate`,
 * `KnowledgePublicationRecord`, `KnowledgePublicationStore`, `KnowledgePublicationOptions`,
 * `KnowledgePublication`.
 */
import type { KnowledgeDocument, KnowledgeRead } from './knowledge.js';
import type { MaybePromise, OperationContext } from '../common.js';

/** Operation names accepted by the publication `authorize` hook. */
export const knowledgePublicationOperations = ['propose', 'publish', 'reject'] as const;

/** Citation of the material a candidate was derived from. */
export interface KnowledgeSourceReference {
  /** Source identity, for example a stored document or manual id. */
  readonly id: string;
  /** Revision of that source that was read. */
  readonly revision: string;
  /** Optional expiry instant; a stale source invalidates the candidate. */
  readonly expiresAtMs?: number;
}

/** A proposed document awaiting publish or reject. */
export interface KnowledgeCandidate {
  /** Candidate id, generated by the Kit. */
  readonly id: string;
  /** Record revision the candidate was proposed against, used for stale-proposal detection. */
  readonly baseRevision: number;
  /** Complete document that would replace the published revision with the same id. */
  readonly document: KnowledgeDocument;
  /** Provenance the candidate depends on; verified by the App, never trusted from the model. */
  readonly sources: readonly KnowledgeSourceReference[];
  readonly createdAtMs: number;
  /** Instant after which the candidate is discarded. */
  readonly expiresAtMs: number;
}

/** Stored publication state: one published revision plus pending candidates. */
export interface KnowledgePublicationRecord {
  /** Monotonic record revision; every accepted mutation increments it. */
  readonly revision: number;
  /** Revision number of the currently published document set. */
  readonly publishedRevision: number;
  /** Published documents, in catalog order. */
  readonly documents: readonly KnowledgeDocument[];
  /** Pending candidates; expired entries are removed before use. */
  readonly candidates: readonly KnowledgeCandidate[];
}

/** Single-writer store for the publication record. */
export interface KnowledgePublicationStore {
  /** Returns the current record; it must always be readable. */
  load(): Promise<KnowledgePublicationRecord>;
  /** Atomically replaces the record when the stored revision still equals `expectedRevision`. */
  compareAndSwap(expectedRevision: number, next: KnowledgePublicationRecord): Promise<boolean>;
}

/** App-owned guards, store and limits for a publication workflow. */
export interface KnowledgePublicationOptions<App> {
  readonly store: KnowledgePublicationStore;
  /** Reads that must succeed against every compiled document set, proving sections still exist. */
  readonly requiredReads?: readonly KnowledgeRead[];
  /** Per-read character budget applied by the catalog compiler. */
  readonly maxReadChars?: number;
  /** Maximum pending candidates retained; defaults to 32 and must be a positive integer. */
  readonly maxCandidates?: number;
  /** Candidate retention window; defaults to seven days. */
  readonly candidateRetentionMs?: number;
  /** Clock override for timestamps and expiry; defaults to `Date.now`. */
  readonly now?: () => number;
  /** Guards one operation before any read or write. */
  authorize(
    operation: (typeof knowledgePublicationOperations)[number],
    context: OperationContext<App>,
  ): MaybePromise<void>;
  /** Validate real provenance/revisions/visibility. A model's source list is not a grant. */
  verifySources(
    sources: readonly KnowledgeSourceReference[],
    context: OperationContext<App>,
  ): MaybePromise<void>;
}

/** Compiled publication workflow. */
export interface KnowledgePublication<App> {
  /** Returns the current record, with expired candidates already pruned. */
  read(context: OperationContext<App>): Promise<KnowledgePublicationRecord>;
  /** Adds a candidate based on `revision`; fails when the record moved on. */
  propose(
    request: {
      revision: number;
      document: KnowledgeDocument;
      sources: readonly KnowledgeSourceReference[];
    },
    context: OperationContext<App>,
  ): Promise<KnowledgePublicationRecord>;
  /** Publishes one candidate and removes it from the pending list. */
  publish(
    request: { revision: number; candidateId: string },
    context: OperationContext<App>,
  ): Promise<KnowledgePublicationRecord>;
  /** Discards one candidate without touching the published documents. */
  reject(
    request: { revision: number; candidateId: string },
    context: OperationContext<App>,
  ): Promise<KnowledgePublicationRecord>;
}
