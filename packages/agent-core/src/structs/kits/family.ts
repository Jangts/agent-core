/**
 * Branch-versioning contracts: immutable App-state versions and a CAS-protected active pointer.
 *
 * Place in the package: an optional App-side library that versions App state hanging off Core
 * branches. A branch-version record is a bounded, expiring collection of immutable versions; the Kit owns revision
 * checks, capacity, retention and lineage rules, while the store, authorization, validation and
 * merge policy stay with the App. No executable function or authority is restored here.
 *
 * Exports: `branchVersionOperations`, `BranchVersionOperation`, `BranchVersion`, `BranchVersionRecord`, `BranchVersionStore`,
 * `BranchVersioningDefinition`, `BranchVersioning`.
 */
import type { OperationContext, MaybePromise } from '../common.js';
import type { AgentBranch } from '../../execution/engine.js';

/** Operation names accepted by the family `authorize` hook. */
export const branchVersionOperations = ['create', 'fork', 'merge', 'promote'] as const;
/** One of the four family mutations. */
export type BranchVersionOperation = (typeof branchVersionOperations)[number];

/** Immutable snapshot of App state at one point on a branch. */
export interface BranchVersion<State> {
  /** Unique version id, generated by the Kit. */
  readonly id: string;
  /** Version this one was forked or merged from, when lineage applies. */
  readonly parentId?: string;
  /** Source version of a merge; present only on versions created by `merge`. */
  readonly mergeSourceId?: string;
  /** Common ancestor recorded for fork/merge bookkeeping. */
  readonly baseId?: string;
  /** Core branch snapshot paired with this state. */
  readonly branch: AgentBranch;
  /** App state; treated as immutable by the Kit and snapshotted on write. */
  readonly state: State;
  /** Creation instant in epoch milliseconds. */
  readonly createdAtMs: number;
}

/** A whole family: its versions and which version is currently active. */
export interface BranchVersionRecord<State> {
  /** BranchVersions id; also the store key. */
  readonly id: string;
  /** Optimistic concurrency token; every accepted mutation increments it by one. */
  readonly revision: number;
  /** Id of the active version; promotion moves this pointer. */
  readonly activeId: string;
  /** Instant after which the record is no longer retained, in epoch milliseconds. */
  readonly expiresAtMs: number;
  /** Versions in creation order; bounded by `maxVersions` when configured. */
  readonly versions: readonly BranchVersion<State>[];
}

/** CAS must cover every writer and the active pointer in one real storage commit. */
export interface BranchVersionStore<State> {
  /** Returns the record, or `undefined` when it does not exist. */
  load(id: string): Promise<BranchVersionRecord<State> | undefined>;
  /** Commits `next` only when the stored revision equals `expectedRevision`; returns success. */
  compareAndSwap(
    id: string,
    expectedRevision: number | undefined,
    next: BranchVersionRecord<State>,
  ): Promise<boolean>;
}

/** App-owned hooks and limits for one family. */
export interface BranchVersioningDefinition<State, App> {
  readonly store: BranchVersionStore<State>;
  /** Maximum retained versions; older versions are dropped once the bound is exceeded. */
  readonly maxVersions?: number;
  /** Retention window in milliseconds, measured from a write. */
  readonly retentionMs?: number;
  /** Clock override for timestamps and expiry; defaults to `Date.now`. */
  readonly now?: () => number;
  /** Validates a state loaded from the store before it is used. */
  isState(value: unknown): value is State;
  /** Guards one mutation; called before any write, including with an absent record. */
  authorize(
    operation: BranchVersionOperation,
    record: BranchVersionRecord<State> | undefined,
    context: OperationContext<App>,
  ): MaybePromise<void>;
  /** Validates a candidate version before it is appended. */
  validate(candidate: BranchVersion<State>, context: OperationContext<App>): MaybePromise<void>;
  /**
   * Resolves a three-way merge.
   *
   * Returns the merged state and any conflicts. A non-empty conflict list aborts the merge without
   * writing a version, so `value` is ignored in that case.
   */
  merge?(
    input: { base: State; target: State; source: State },
    context: OperationContext<App>,
  ): MaybePromise<{ value?: State; conflicts: readonly string[] }>;
}

/** Compiled family API. Every mutation returns the record after the write. */
export interface BranchVersioning<State, App> {
  /** Reads the record; throws when the family does not exist or has expired. */
  read(id: string, context: OperationContext<App>): Promise<BranchVersionRecord<State>>;
  /** Creates the first version and makes it active. */
  create(
    request: { id: string; branch: AgentBranch; state: State },
    context: OperationContext<App>,
  ): Promise<BranchVersionRecord<State>>;
  /** Appends a version forked from `parentId`; the active pointer does not change. */
  fork(
    request: { id: string; revision: number; parentId: string; branch: AgentBranch; state: State },
    context: OperationContext<App>,
  ): Promise<BranchVersionRecord<State>>;
  /** Merges `source` into `target`; `saved` is false when the merge reported conflicts. */
  merge(
    request: { id: string; revision: number; baseId: string; targetId: string; sourceId: string },
    context: OperationContext<App>,
  ): Promise<{ saved: boolean; record: BranchVersionRecord<State>; conflicts: readonly string[] }>;
  /** Makes `candidateId` active; fails when the active version changed since `expectedActiveId`. */
  promote(
    request: { id: string; revision: number; candidateId: string; expectedActiveId: string },
    context: OperationContext<App>,
  ): Promise<BranchVersionRecord<State>>;
}

